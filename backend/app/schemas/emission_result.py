import datetime
from typing import Optional
from pydantic import BaseModel, Field


class CategoryPercentages(BaseModel):
    electricity: float = Field(..., description="Percentage contribution from electricity (0 to 100)")
    fuel: float = Field(..., description="Percentage contribution from fuel (0 to 100)")
    material: float = Field(..., description="Percentage contribution from raw materials (0 to 100)")
    waste: float = Field(..., description="Percentage contribution from solid waste (0 to 100)")


class HotspotInfo(BaseModel):
    category: str = Field(..., description="Name of the emission hotspot category or 'No hotspot'")
    value: float = Field(..., description="Total CO2e emissions generated by the hotspot category (kg CO2e)")
    percentage: float = Field(..., description="Hotspot percentage contribution to total factory emissions")


class EmissionResultBase(BaseModel):
    electricity_co2: float = Field(default=0.0, description="Emissions from electricity in kg CO2e")
    fuel_co2: float = Field(default=0.0, description="Emissions from fuel combustion in kg CO2e")
    material_co2: float = Field(default=0.0, description="Emissions from raw materials in kg CO2e")
    waste_co2: float = Field(default=0.0, description="Emissions from solid waste in kg CO2e")
    total_co2: float = Field(default=0.0, description="Total greenhouse gas emissions in kg CO2e")


class EmissionResultResponse(EmissionResultBase):
    id: int = Field(..., description="Unique emission result record ID")
    factory_data_id: int = Field(..., description="Associated factory data submission ID")
    created_at: Optional[datetime.datetime] = Field(None, description="Timestamp of emission calculation")
    percentages: Optional[CategoryPercentages] = Field(None, description="Category percentage breakdown")
    hotspot: Optional[HotspotInfo] = Field(None, description="Identified emission hotspot analysis")

    model_config = {"from_attributes": True}
